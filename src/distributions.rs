use core::f64;

use libm::{erf, exp, fabs, log, sqrt};

/// Cumulative distribution function.  P(X <= x)
pub fn cdf(x: f64, mu: f64, sigma: f64) -> f64 {
    if sigma < 0.0 {
        return f64::NAN; // sigma must be non-negative
    }

    if sigma == 0.0 {
        return f64::NAN; // Err("cdf() not defined when sigma is zero");
    }

    0.5 * (1.0 + erf((x - mu) / (sigma * f64::consts::SQRT_2)))
}

/// Probability density function.  P(x <= X < x+dx) / dx
pub fn pdf(x: f64, mu: f64, sigma: f64) -> f64 {
    if sigma < 0.0 {
        return f64::NAN; // sigma must be non-negative
    }

    let variance = sigma * sigma;
    if variance == 0.0 {
        return f64::NAN; // pdf() not defined when sigma is zero
    }

    let diff = x - mu;

    exp(diff * diff / (-2.0 * variance)) / sqrt(f64::consts::TAU * variance)
}

fn r8poly_value(n: usize, a: &[f64], x: f64) -> f64 {
    let mut value = 0.0;

    for i in (0..n).rev() {
        value = value * x + a[i];
    }

    return value;
}

pub fn inv_cdf(p: f64) -> f64 {
    const a: [f64; 8] = [
        3.3871328727963666080,
        1.3314166789178437745e+2,
        1.9715909503065514427e+3,
        1.3731693765509461125e+4,
        4.5921953931549871457e+4,
        6.7265770927008700853e+4,
        3.3430575583588128105e+4,
        2.5090809287301226727e+3,
    ];
    const b: [f64; 8] = [
        1.0,
        4.2313330701600911252e+1,
        6.8718700749205790830e+2,
        5.3941960214247511077e+3,
        2.1213794301586595867e+4,
        3.9307895800092710610e+4,
        2.8729085735721942674e+4,
        5.2264952788528545610e+3,
    ];
    const c: [f64; 8] = [
        1.42343711074968357734,
        4.63033784615654529590,
        5.76949722146069140550,
        3.64784832476320460504,
        1.27045825245236838258,
        2.41780725177450611770e-1,
        2.27238449892691845833e-2,
        7.74545014278341407640e-4,
    ];
    const const1: f64 = 0.180625;
    const const2: f64 = 1.6;
    const d: [f64; 8] = [
        1.0,
        2.05319162663775882187,
        1.67638483018380384940,
        6.89767334985100004550e-1,
        1.48103976427480074590e-1,
        1.51986665636164571966e-2,
        5.47593808499534494600e-4,
        1.05075007164441684324e-9,
    ];
    const e: [f64; 8] = [
        6.65790464350110377720,
        5.46378491116411436990,
        1.78482653991729133580,
        2.96560571828504891230e-1,
        2.65321895265761230930e-2,
        1.24266094738807843860e-3,
        2.71155556874348757815e-5,
        2.01033439929228813265e-7,
    ];
    const f: [f64; 8] = [
        1.0,
        5.99832206555887937690e-1,
        1.36929880922735805310e-1,
        1.48753612908506148525e-2,
        7.86869131145613259100e-4,
        1.84631831751005468180e-5,
        1.42151175831644588870e-7,
        2.04426310338993978564e-15,
    ];
    const split1: f64 = 0.425;
    const split2: f64 = 5.0;

    if p <= 0.0 {
        return -1.0E+30;
    } else if 1.0 <= p {
        return 1.0E+30;
    }

    let q = p - 0.5;

    if fabs(q) <= split1 {
        let r = const1 - q * q;
        return q * r8poly_value(8, &a, r) / r8poly_value(8, &b, r);
    } else {
        let mut r = if q < 0.0 { p } else { 1.0 - p };

        if r <= 0.0 {
            return f64::NAN;
        }

        r = sqrt(-log(r));

        let mut value = if r <= split2 {
            r = r - const2;
            r8poly_value(8, &c, r) / r8poly_value(8, &d, r)
        } else {
            r = r - split2;
            r8poly_value(8, &e, r) / r8poly_value(8, &f, r)
        };

        if q < 0.0 {
            value = -value;
        }

        value
    }
}

