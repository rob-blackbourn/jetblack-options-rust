use libm::{fabs, log};

/// # cndev
///
/// Inverse cumulative normal distribution function
#[allow(non_snake_case)]
pub fn cndev(U: f64) -> f64 {
    const A: [f64; 4] = [
        2.50662823884,
        -18.61500062529,
        41.39119773534,
        -25.44106049637,
    ];
    const B: [f64; 4] = [
        -8.4735109309,
        23.08336743743,
        -21.06224101826,
        3.13082909833,
    ];
    const C: [f64; 9] = [
        0.337475482272615,
        0.976169019091719,
        0.160797971491821,
        2.76438810333863E-02,
        3.8405729373609E-03,
        3.951896511919E-04,
        3.21767881767818E-05,
        2.888167364E-07,
        3.960315187E-07,
    ];

    let x = U - 0.5;
    if fabs(x) < 0.92 {
        let r = x * x;
        let r = x * (((A[3] * r + A[2]) * r + A[1]) * r + A[0])
            / ((((B[3] * r + B[2]) * r + B[1]) * r + B[0]) * r + 1.0);
        return r;
    }

    let r = if x < 0.0 { U } else { 1.0 - U };
    let r = log(-log(r));
    let r = C[0]
        + r * (C[1]
            + r * (C[2]
                + r * (C[3] + r + (C[4] + r * (C[5] + r * (C[6] + r * (C[7] + r * C[8])))))));
    if r >= 0.0 { r } else { -r }
}
